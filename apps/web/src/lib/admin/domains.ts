import { slugSchema, type Domain, type UpdateDomainInput } from '@coursecraft/shared';
import { z } from 'zod';

/** What the domain dialog edits. Empty strings mean "not set". */
export const domainFormSchema = z.object({
  name: z.string().trim().min(2, 'Name must be at least 2 characters').max(60),
  description: z.string().trim().max(500, 'At most 500 characters'),
  slug: z.union([z.literal(''), slugSchema]),
});
export type DomainForm = z.infer<typeof domainFormSchema>;

export const emptyDomainForm: DomainForm = { name: '', description: '', slug: '' };

export const domainToForm = (domain: Domain): DomainForm => ({
  name: domain.name,
  description: domain.description ?? '',
  slug: domain.slug,
});

/** Body for `POST /domains`: the slug is generated by the API when left empty. */
export function createBody(form: DomainForm) {
  return {
    name: form.name.trim(),
    ...(form.description.trim() && { description: form.description.trim() }),
    ...(form.slug && { slug: form.slug }),
  };
}

/** Body for `PATCH /domains/:id` with only what changed; `null` when nothing did. */
export function updateBody(original: Domain, form: DomainForm): UpdateDomainInput | null {
  const body: UpdateDomainInput = {};
  if (form.name.trim() !== original.name) body.name = form.name.trim();
  const description = form.description.trim() || null;
  if (description !== original.description) body.description = description;
  if (form.slug && form.slug !== original.slug) body.slug = form.slug;
  return Object.keys(body).length > 0 ? body : null;
}

/**
 * Cache tags of the public catalog (lib/catalog.ts) that a domain change makes stale: the
 * domain list, the domain's page under its old and new slug, and course pages (their breadcrumb
 * shows the domain).
 */
export function catalogTagsFor(...slugs: (string | undefined)[]): string[] {
  const unique = [...new Set(slugs.filter((s): s is string => Boolean(s)))];
  return ['domains', 'courses', ...unique.map((slug) => `domain:${slug}`)];
}
